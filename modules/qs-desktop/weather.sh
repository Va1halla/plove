#!/bin/sh
# Сгенерировано plove: погода для карточек «Погода» на рабочем столе.
# Печатает JSON wttr.in (format=j1: сейчас и прогноз на три дня, описание
# по-русски). Нет связи — пустой вывод, карточка покажет «нет связи».
# $1 — город (пусто — wttr.in определит по IP).
city=$(printf '%s' "$1" | sed 's/ /+/g')
curl -sf --max-time 15 "https://wttr.in/${city}?format=j1&lang=ru"
